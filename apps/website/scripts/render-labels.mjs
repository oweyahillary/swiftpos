// Renders the site's barcode labels through the REAL label code (shared/labels.ts and shared/barcode.ts, A571/A574,
// read only), so the labels on the website are exactly what ZapTill prints: the same layout, the same bars, the same
// in-store EAN-13 codes. Made-up demo shop only ("Demo Mini Mart"); never a client's items or prices.
//
// Run from apps/website (Node 24 reads the .ts files directly):
//   npm run labels
// It writes src/lib/labels.generated.json, which src/components/screens/LabelSamples.astro reads.
// test/labels.test.mjs fails if that file drifts from shared/labels.ts: re-run this script when the label code changes.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const shared = join(here, '../../../shared');
const L = await import(pathToFileURL(join(shared, 'labels.ts')).href);
const B = await import(pathToFileURL(join(shared, 'barcode.ts')).href);

// The demo shop's items. The codes are ZapTill's own in-store numbers (prefix 20, the next free numbers, A571), as
// "Generate barcodes" gives them to products that have none.
const codes = B.nextInStoreCodes([], 3);
const items = [
  { name: 'Cooking Oil 1L', price: 340, code: codes[0] },
  { name: 'Bar Soap 800g', price: 240, code: codes[1] },
  { name: 'Biscuits 200g', price: 120, code: codes[2] },
];
const business = 'Demo Mini Mart';

const base = L.cleanLabelSettings({});

/** One label, as the SVG every print path draws from (the browser page, the sticker sheet). */
function label(item, widthMm, heightMm, extra = {}) {
  const settings = L.cleanLabelSettings({ ...base, widthMm, heightMm, ...extra });
  const bars = B.encodeBarcode(item.code);
  const l = L.layoutLabel(settings, { name: item.name, price: item.price, currency: 'KES', business }, bars);
  return { name: item.name, code: item.code, widthMm, heightMm, svg: L.labelSvg(l), warnings: l.warnings };
}

export function renderLabels() {
  const rolls = [
    { ...label(items[0], 50, 30), printer: 'A label printer, 50 × 30 mm' },
    { ...label(items[1], 58, 40, { showBusiness: true }), printer: 'A label printer, 58 × 40 mm, with the shop’s name' },
    { ...label(items[2], 38, 25), printer: 'A small label, 38 × 25 mm' },
  ];
  // An A4 sheet of 3 × 8 stickers (the common L7159 layout), the first two rows used.
  const sheet = { ...L.SHEET_PRESETS['3x8'] };
  const grid = L.sheetGrid(sheet);
  const svgs = [0, 1, 2, 0, 1, 2].map((i) => {
    const s = L.cleanLabelSettings({ ...base });
    const l = L.layoutLabel(s, { name: items[i].name, price: items[i].price, currency: 'KES', business }, B.encodeBarcode(items[i].code),
      { widthMm: sheet.labelWidthMm, heightMm: sheet.labelHeightMm });
    return L.labelSvg(l);
  });
  return {
    note: 'Generated by scripts/render-labels.mjs from shared/labels.ts and shared/barcode.ts. Do not edit by hand.',
    codes,
    rolls,
    sheet: {
      preset: '3x8', pageWidthMm: grid.pageWidthMm, pageHeightMm: grid.pageHeightMm,
      cells: grid.cells.map((c) => ({ x: c.x, y: c.y, w: c.w, h: c.h })),
      svgs,
    },
  };
}

export const LABELS_FILE = join(here, '../src/lib/labels.generated.json');

if (process.argv[1]?.endsWith('render-labels.mjs')) {
  const out = renderLabels();
  writeFileSync(LABELS_FILE, JSON.stringify(out, null, 2) + '\n');
  for (const r of out.rolls) console.log(`${r.widthMm}x${r.heightMm} ${r.name} ${r.code} ${r.svg.length} chars${r.warnings.length ? ' warnings: ' + r.warnings.join('; ') : ''}`);
  console.log(`sheet ${out.sheet.preset}: ${out.sheet.cells.length} cells, ${out.sheet.svgs.length} used`);
}
