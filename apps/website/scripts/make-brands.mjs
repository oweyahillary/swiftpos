// Renders the FICTIONAL demo brands (src/assets/demo-brands/*.svg, brands.json) for the site, the till shots and the
// receipts. Run from apps/website (after building shared/printing): node scripts/make-brands.mjs
//   public/demo-brands/<id>.png          the colour logo, 680x200 @2x, transparent (site, video stage)
//   public/demo-brands/<id>-mark.png     the mark alone, 400x400 (the till's logo, small places)
//   public/demo-brands/<id>-receipt.png  the receipt logo exactly as the printer prints it: the mono raster below,
//                                        fitted by shared/printing's fitMonoRaster (384 x 120 dots), one pixel a dot
//   src/lib/demo-brands.rasters.json     each brand's receipt logo as the product stores it (logo_receipt: a mono1 string
//                                        from monoRasterFromRGBA, as the dashboard's BrandingTab makes it)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(process.cwd() + '/package.json');
const sharp = require('sharp');
const P = require(join(here, '../../../shared/printing/dist/index.js'));
const { monoRasterFromRGBA, monoRasterToString, fitMonoRaster, RECEIPT_LOGO_MAX_WIDTH, RECEIPT_LOGO_MAX_HEIGHT, RECEIPT_LOGO_PRINT_MAX_HEIGHT } = P;

const SRC = join(here, '../src/assets/demo-brands');
const OUT = join(here, '../public/demo-brands');
mkdirSync(OUT, { recursive: true });
const { brands } = JSON.parse(readFileSync(join(SRC, 'brands.json'), 'utf8'));

/** 1-bit raster -> a black-on-white PNG, one pixel per printer dot. */
async function rasterPng(r, file) {
  const px = Buffer.alloc(r.width * r.height);
  const row = Math.ceil(r.width / 8);
  for (let y = 0; y < r.height; y++) for (let x = 0; x < r.width; x++) {
    const on = (r.bytes[y * row + (x >> 3)] >> (7 - (x & 7))) & 1;
    px[y * r.width + x] = on ? 0 : 255;
  }
  await sharp(px, { raw: { width: r.width, height: r.height, channels: 1 } }).png({ palette: true, colours: 2 }).toFile(file);
}

const rasters = { note: 'Generated by scripts/make-brands.mjs from src/assets/demo-brands/*-mono.svg through shared/printing. Do not edit by hand.' };
for (const b of brands) {
  const svg = readFileSync(join(SRC, `${b.id}.svg`));
  await sharp(svg, { density: 144 }).resize({ width: 1360 }).png().toFile(join(OUT, `${b.id}.png`));
  // The mark alone: the left 200 x 200 of the lockup.
  const big = await sharp(svg, { density: 288 }).resize({ width: 2720, height: 800, fit: 'fill' }).png().toBuffer();
  const mark = await sharp(big).extract({ left: 0, top: 0, width: 800, height: 800 }).png().toBuffer();
  await sharp(mark).resize({ width: 400 }).png().toFile(join(OUT, `${b.id}-mark.png`));
  // The receipt logo: the mono SVG drawn at the stored size, then the product's own conversion.
  const mono = readFileSync(join(SRC, `${b.id}-mono.svg`));
  const w = RECEIPT_LOGO_MAX_WIDTH, h = Math.round((w * 200) / 680);
  const { data } = await sharp(mono).resize({ width: w, height: h }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const stored = monoRasterFromRGBA(data, w, h, { maxWidth: RECEIPT_LOGO_MAX_WIDTH, maxHeight: RECEIPT_LOGO_MAX_HEIGHT });
  rasters[b.id] = monoRasterToString(stored);
  await rasterPng(fitMonoRaster(stored, RECEIPT_LOGO_MAX_WIDTH, RECEIPT_LOGO_PRINT_MAX_HEIGHT), join(OUT, `${b.id}-receipt.png`));
  console.log('brand', b.id, `${stored.width}x${stored.height}`);
}
writeFileSync(join(here, '../src/lib/demo-brands.rasters.json'), JSON.stringify(rasters, null, 2) + '\n');
