#!/usr/bin/env node
/**
 * build-light-colours.mjs — A333 (2026-09-27): light mode for the dashboard's COLOURED and pale text, and its translucent
 * gray lines. Writes ONE generated block into apps/dashboard/src/index.css (between the BEGIN/END markers).
 *
 * Why generated: light mode is a hand-kept list of per-class overrides (index.css) that only ever covered grays. The
 * dashboard uses ~300 colour classes; ~20 text colours sat below 4.5:1 on white (green-400 1.74, red-400 2.77, amber-400 1.67,
 * gray-200 1.24 …) and translucent gray borders stayed dark. This emits a rule for every such class the source USES:
 *   - coloured text 300–500 → the same colour's 700 (800 where the 700 fails on its own tint; hover one deeper): same meaning (green = success, red = problem), ≥ 4.5:1
 *     (100–200 are pale LABELS on coloured fills — e.g. teal-100 on the teal accent cards — and are left alone);
 *   - pale gray text 100/200/300 → slate 800/700/600;
 *   - translucent gray borders / dividers / fills → the light theme's grays at the same alpha.
 * Scope: light mode only, and NOT inside a web POS set to dark ([data-pos-theme="dark"]) or a screen that is always dark
 * ([data-theme-lock="dark"] — sign-in, onboarding, password change). Inside a locked screen it also RESTORES the classes the
 * older gray overrides had turned dark (their white text turned slate on navy).
 * A332 (2026-09-27) — also, for light mode:
 *   - WHITE LABELS STAY WHITE on a solid fill where white reads better than the slate the light theme turns .text-white
 *     into (computed per fill the source pairs with text-white: red-600, the theme's action-600 …; green-500 etc. read
 *     better in slate and are left to it);
 *   - the web POS's action-button HOVER (hover:bg-action-400 on dark-label 500 fills) uses the theme's 400 FILL
 *     (--action-d-400), not the link-text shade light mode gives --action-400 (teal 700: 3.26:1 under a dark label);
 *   - the themed focus ring (focus:border-action-500) — A328's rule sat inside @layer base and never reached the build.
 * OUTSIDE @layer base on purpose: Tailwind drops rules written for variant classes there (A329).
 *
 *   node scripts/build-light-colours.mjs          # rewrite the block
 *   node scripts/build-light-colours.mjs --check  # CI: exit 1 if the block is stale (a new class has no light rule)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'apps/dashboard/src');
const CSS = path.join(SRC, 'index.css');
const BEGIN = '/* ── BEGIN light-colours (generated by scripts/build-light-colours.mjs — do not edit by hand) ── */';
const END = '/* ── END light-colours ── */';

// Tailwind v3 palette — the 700 / 800 shades used for text on light surfaces.
export const SHADE = {
  red: ['#b91c1c', '#991b1b'], green: ['#166534', '#14532d'], amber: ['#92400e', '#78350f'], yellow: ['#854d0e', '#713f12'],   // amber/yellow/green/orange/cyan/lime: 800 — their 700 fell short on their own denser tints (/15, /20: 4.22–4.47)
  blue: ['#1d4ed8', '#1e40af'], purple: ['#7e22ce', '#6b21a8'], orange: ['#9a3412', '#7c2d12'], emerald: ['#047857', '#065f46'],
  sky: ['#0369a1', '#075985'], indigo: ['#4338ca', '#3730a3'], pink: ['#be185d', '#9d174d'], teal: ['#0f766e', '#115e59'],
  cyan: ['#155e75', '#164e63'], violet: ['#6d28d9', '#5b21b6'], rose: ['#be123c', '#9f1239'], lime: ['#3f6212', '#365314'],
};
export const PALE_GRAY = { 100: '#1e293b', 200: '#334155', 300: '#475569' };        // slate 800 / 700 / 600
const LINE = '226,232,240';   // #e2e8f0 — the light theme's border gray (index.css)
const FILL = '241,245,249';   // #f1f5f9 — its gray-800 surface
const TW_DARK = { 'text-white': '#ffffff', 'text-gray-300': '#d1d5db', 'text-gray-400': '#9ca3af', 'text-gray-500': '#6b7280',
  'text-gray-600': '#4b5563', 'bg-gray-800': '#1f2937', 'bg-gray-900': '#111827', 'bg-gray-950': '#030712', 'bg-gray-700': '#374151',
  'border-gray-700': '#374151', 'border-gray-800': '#1f2937', 'placeholder-gray-600': '#4b5563', 'placeholder-gray-500': '#6b7280' };
const LOCKED = ['pages/LoginPage.tsx', 'pages/OnboardingPage.tsx', 'pages/ForcePasswordChangePage.tsx'];

// Solid fills (Tailwind v3 hex) a white label can sit on; the theme fills are CSS variables — their white-label shade is
// the theme's 700, proven >= 5.36:1 for all seven themes (A328), so white always wins there.
export const FILL_HEX = {
  'red-500': '#ef4444', 'red-600': '#dc2626', 'red-700': '#b91c1c', 'green-500': '#22c55e', 'green-600': '#16a34a', 'green-700': '#15803d',
  'amber-500': '#f59e0b', 'amber-600': '#d97706', 'blue-500': '#3b82f6', 'blue-600': '#2563eb', 'blue-700': '#1d4ed8',
  'purple-600': '#9333ea', 'orange-500': '#f97316', 'orange-600': '#ea580c', 'emerald-600': '#059669', 'indigo-600': '#4f46e5',
  'yellow-500': '#eab308', 'teal-600': '#0d9488', 'teal-700': '#0f766e',
};
export const THEME_WHITE_FILLS = ['action-600'];
export const SLATE = '#0f172a';   // what the light theme turns .text-white into (index.css)
export function contrast(a, b) {
  const lum = (h) => { const v = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((x) => (x <= 0.03928 ? x / 12.92 : ((x + 0.055) / 1.055) ** 2.4)); return 0.2126 * v[0] + 0.7152 * v[1] + 0.0722 * v[2]; };
  const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);
}

/** Solid fills the source pairs with text-white in the SAME class string. */
export function whiteLabelFills() {
  const found = new Set();
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { walk(p); continue; }
      if (!/\.tsx$/.test(e.name)) continue;
      for (const line of fs.readFileSync(p, 'utf8').split('\n')) for (const seg of line.split(/['"`]/)) {
        if (!/(?<![\w:-])text-white(?![\w/-])/.test(seg)) continue;
        for (const m of seg.matchAll(/(?<![\w:-])bg-((?:[a-z]+-[5-9]00)|action-600)(?![\w/-])/g)) found.add(m[1]);
      }
    }
  })(SRC);
  return [...found].sort();
}

const esc = (c) => c.replace(/([:/.[\]#])/g, '\\$1');
const NOT = ':not([data-pos-theme="dark"] *):not([data-theme-lock="dark"] *)';

export function usedClasses() {
  const used = new Map();
  (function walk(d) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) { walk(p); continue; }
      if (!/\.tsx?$/.test(e.name)) continue;
      const rel = path.relative(SRC, p).split(path.sep).join('/');
      for (const m of fs.readFileSync(p, 'utf8').matchAll(/(?<![\w:-])((?:hover:|group-hover:|focus:)?)(text|border|divide|bg)(-[lrtbxy])?-([a-z]+)-(\d{2,3})(\/\d+)?(?![\w/-])/g)) {
        const c = m[0]; if (!used.has(c)) used.set(c, new Set()); used.get(c).add(rel);
      }
    }
  })(SRC);
  return used;
}

export function buildBlock(css = fs.readFileSync(CSS, 'utf8')) {
  const used = usedClasses();
  // Classes the hand-kept overrides already handle (outside this block) are left to them.
  const outside = css.includes(BEGIN) ? css.slice(0, css.indexOf(BEGIN)) + css.slice(css.indexOf(END) + END.length) : css;
  const handled = new Set([...outside.matchAll(/:root:not\(\.dark\)\s+\.((?:[\w-]|\\[:/.])+)/g)].map((m) => m[1].replace(/\\/g, '')));
  const rules = [];
  for (const c of [...used.keys()].sort()) {
    if (handled.has(c)) continue;
    const m = c.match(/^((?:hover:|group-hover:)?)(text|border|divide|bg)(-[lrtbxy])?-([a-z]+)-(\d{2,3})(\/\d+)?$/);
    if (!m) continue;   // focus: classes are only collected for the A332 rules below
    const [, pre, util, side = '', colour, shadeS, alphaS] = m; const shade = +shadeS;
    const a = alphaS ? +alphaS.slice(1) / 100 : null;
    const state = pre === 'hover:' ? ':hover' : '';
    const sel = pre === 'group-hover:' ? `:root:not(.dark) .group:hover .${esc(c)}${NOT}` : `:root:not(.dark) .${esc(c)}${state}${NOT}`;
    let decl = null;
    if (util === 'text' && SHADE[colour] && shade >= 300 && shade <= 500) {
      const hex = SHADE[colour][pre ? 1 : 0];
      decl = a == null ? `color: ${hex}` : `color: ${hex}${Math.round(a * 255).toString(16).padStart(2, '0')}`;
    } else if (util === 'text' && colour === 'gray' && PALE_GRAY[shade] && !a) {
      decl = `color: ${PALE_GRAY[shade]}`;
    } else if ((util === 'border' || util === 'divide') && colour === 'gray' && a != null && shade >= 600) {
      decl = `border-color: rgba(${LINE},${Math.max(a, 0.6)})`;
    } else if (util === 'bg' && colour === 'gray' && a != null && shade >= 700) {
      decl = `background-color: rgba(${FILL},${a})`;
    }
    if (!decl) continue;
    const s = util === 'divide' ? sel.replace(`.${esc(c)}`, `.${esc(c)} > * + *`) : sel;
    rules.push(`${s} { ${decl} !important; }`);
  }
  // A332: white labels stay white where white beats slate on that fill.
  for (const f of whiteLabelFills()) {
    const white = THEME_WHITE_FILLS.includes(f) || (FILL_HEX[f] && contrast('#ffffff', FILL_HEX[f]) >= contrast(SLATE, FILL_HEX[f]));
    if (!white) continue;
    const c = esc(`bg-${f}`);
    rules.push(`:root:not(.dark) .${c}.text-white, :root:not(.dark) .${c} .text-white { color: #ffffff !important; }`);
  }
  // A332: the action hover fill under a dark label = the theme's 400 FILL in light mode too (not the link-text shade).
  if (used.has('hover:bg-action-400')) rules.push(`:root:not(.dark) .hover\\:bg-action-400:hover, [data-pos-theme="light"] .hover\\:bg-action-400:hover { background-color: rgb(var(--action-d-400, 45 212 191)) !important; }`);
  // A332: the themed focus ring in light mode (A328's rule sat inside @layer base and never compiled).
  if (used.has('focus:border-action-500') || [...used.keys()].some((k) => k === 'focus:border-action-500')) rules.push(`:root:not(.dark) .focus\\:border-action-500:focus { border-color: rgb(var(--action-500)) !important; }`);
  // Always-dark screens: undo the older gray overrides for the classes they use.
  const restore = new Set();
  for (const f of LOCKED) {
    const t = fs.readFileSync(path.join(SRC, f), 'utf8');
    for (const k of Object.keys(TW_DARK)) if (new RegExp(`(?<![\\w:-])${k.replace(/-/g, '\\-')}(?![\\w/-])`).test(t)) restore.add(k);
  }
  for (const k of [...restore].sort()) {
    const prop = k.startsWith('text-') ? 'color' : k.startsWith('bg-') ? 'background-color' : k.startsWith('border-') ? 'border-color' : null;
    if (k.startsWith('placeholder-')) rules.push(`:root:not(.dark) [data-theme-lock="dark"] .${esc(k)}::placeholder { color: ${TW_DARK[k]} !important; }`);
    else rules.push(`:root:not(.dark) [data-theme-lock="dark"] .${esc(k)} { ${prop}: ${TW_DARK[k]} !important; }`);
  }
  return `${BEGIN}\n${rules.join('\n')}\n${END}`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const css = fs.readFileSync(CSS, 'utf8');
  const block = buildBlock(css);
  const has = css.includes(BEGIN) && css.includes(END);
  const current = has ? css.slice(css.indexOf(BEGIN), css.indexOf(END) + END.length) : '';
  if (process.argv.includes('--check')) {
    if (current === block) { console.log(`OK — light-colours block is current (${block.split('\n').length - 2} rules).`); }
    else { console.log('STALE — apps/dashboard/src/index.css light-colours block does not match the classes the dashboard uses.\nRun: node scripts/build-light-colours.mjs'); process.exitCode = 1; }
  } else {
    const next = has ? css.replace(current, block) : css.replace('/* ── Smooth theme transition', `${block}\n\n/* ── Smooth theme transition`);
    fs.writeFileSync(CSS, next);
    console.log(`light-colours block written: ${block.split('\n').length - 2} rules.`);
  }
}
